package gregicality.multiblocks.common.block.blocks;

import net.minecraft.block.SoundType;
import net.minecraft.block.material.Material;
import net.minecraft.block.state.IBlockState;
import net.minecraft.entity.EntityLiving;
import net.minecraft.util.IStringSerializable;
import net.minecraft.util.math.BlockPos;
import net.minecraft.world.IBlockAccess;

import org.jetbrains.annotations.NotNull;

import gregtech.api.block.VariantBlock;

public class BlockTieredComponent extends VariantBlock<BlockTieredComponent.CasingType> {

    public BlockTieredComponent() {
        super(Material.IRON);
        setTranslationKey("tiered_component");
        setHardness(5.0f);
        setResistance(10.0f);
        setSoundType(SoundType.METAL);
        setHarvestLevel("wrench", 2);
        setDefaultState(getState(CasingType.COMPONENT_IV));
    }

    @Override
    public boolean canCreatureSpawn(@NotNull IBlockState state, @NotNull IBlockAccess world, @NotNull BlockPos pos,
                                    @NotNull EntityLiving.SpawnPlacementType type) {
        return false;
    }

    public enum CasingType implements IStringSerializable {

        COMPONENT_IV("insane_voltage"),
        COMPONENT_LuV("ludicrous_voltage"),
        COMPONENT_ZPM("zero_point_module"),
        COMPONENT_UV("ultimate_voltage"),
        COMPONENT_UHV("ultra_high_voltage");

        private final String name;

        CasingType(String name) {
            this.name = name;
        }

        @Override
        public @NotNull String getName() {
            return this.name;
        }
    }
}
